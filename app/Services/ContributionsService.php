    function computePagibig($monthlySalary): array
    {
        $base = min($monthlySalary, 5000);
        $employee = $base * 0.02;
        $employer = $base * 0.02;

        return [
            'total' => round($employee + $employer, 2),
            'employee_share' => round($employee, 2),
            'employer_share' => round($employer, 2),
        ];
    }

